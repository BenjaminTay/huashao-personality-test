export const QUESTIONS: Question[] = QUESTION_COPY.map((copy) => {
  const scoring = QUESTION_SCORING_V3[copy.id];
  if (!scoring) throw new Error(`缺少 ${copy.id} 的 V3 评分矩阵`);
  return {
    id: copy.id,
    act: copy.act,
    title: copy.title,
    body: copy.prompt,
    dimensions: scoring.dimensions,
    options: copy.options.map((text, index) => {
      const id = (["A", "B", "C", "D"] as OptionId[])[index];
      return { id, text, scores: scoring.options[id] };
    }) as [QuizOption, QuizOption, QuizOption, QuizOption],
  };
});

export const QUESTION_IDS = QUESTIONS.map((question) => question.id);
